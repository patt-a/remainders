#!/usr/bin/env node
/**
 * Generates lib/statue-image-data.ts from a JPEG or PNG image.
 *
 * Why: @vercel/og (Satori) only decodes PNG, JPEG, GIF and SVG — WebP is
 * rejected silently. Embedding the image as a base64 data URL also means the
 * wallpaper route never has to fetch it over the network, so it works on
 * every deployment (production, preview, local) and in both runtimes.
 *
 * Usage (no dependencies needed):
 *   node scripts/generate-statue-data.mjs public/statue-memento.jpg
 *
 * To change the statue: export your new image as JPEG (or PNG), put it in
 * public/, run this script with its path, then commit the regenerated file.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const input = process.argv[2] || 'public/statue-memento.jpg';
const bytes = readFileSync(resolve(process.cwd(), input));

function jpegSize(buf) {
  if (buf[0] !== 0xff || buf[1] !== 0xd8) return null;
  let i = 2;
  while (i < buf.length) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marker = buf[i + 1];
    const len = buf.readUInt16BE(i + 2);
    // SOF0 / SOF1 / SOF2 (the frame types Satori can read)
    if (marker === 0xc0 || marker === 0xc1 || marker === 0xc2) {
      return { mime: 'image/jpeg', height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
    }
    i += 2 + len;
  }
  return null;
}

function pngSize(buf) {
  const sig = [137, 80, 78, 71, 13, 10, 26, 10];
  if (!sig.every((b, k) => buf[k] === b)) return null;
  return { mime: 'image/png', width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

const info = jpegSize(bytes) || pngSize(bytes);
if (!info) {
  console.error(`Unsupported image: ${input}. Use a JPEG (baseline/progressive) or PNG file.`);
  process.exit(1);
}

const out = `// AUTO-GENERATED by scripts/generate-statue-data.mjs from ${input.replace(/\\/g, '/')}
// Do not edit by hand — re-run the script to change the statue image.

export const STATUE_IMAGE_WIDTH = ${info.width};
export const STATUE_IMAGE_HEIGHT = ${info.height};
export const STATUE_IMAGE_DATA_URL =
  'data:${info.mime};base64,${bytes.toString('base64')}';
`;

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, '..', 'lib', 'statue-image-data.ts');
writeFileSync(target, out);
console.log(`Wrote ${target} (${info.mime}, ${info.width}x${info.height}, ${bytes.length} bytes)`);
